
from pathlib import Path
import subprocess
import sys
import tempfile

import pandas as pd
import streamlit as st

st.set_page_config(
    page_title="BETH Risk Triage MVP",
    page_icon="🛡️",
    layout="wide",
)

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "artifacts" / "baseline.json"

st.title("🛡️ BETH Security Risk Triage")
st.caption("Explainable Security Risk Scoring | Local MVP")

st.sidebar.header("Security Analysis")
st.sidebar.info(
    "Upload BETH security event logs to calculate "
    "risk scores using the existing Python scoring engine."
)

uploaded_file = st.file_uploader(
    "Upload BETH CSV Dataset",
    type=["csv"],
)

if uploaded_file is None:
    st.info("Upload a BETH CSV file to begin analysis.")
    st.stop()

if not BASELINE.exists():
    st.error("Baseline model not found. Run the benchmark first.")
    st.stop()

if st.button("Analyze Security Events", type="primary"):
    with st.spinner("Analyzing security events..."):
        try:
            with tempfile.TemporaryDirectory() as temp_dir:
                temp_path = Path(temp_dir)
                csv_path = temp_path / "uploaded.csv"
                output_path = temp_path / "results"

                csv_path.write_bytes(uploaded_file.getvalue())

                command = [
                    sys.executable,
                    "-m",
                    "src.triage",
                    "score",
                    "--data",
                    str(csv_path),
                    "--baseline",
                    str(BASELINE),
                    "--out",
                    str(output_path),
                ]

                result = subprocess.run(
                    command,
                    cwd=ROOT,
                    capture_output=True,
                    text=True,
                    timeout=120,
                )

                if result.returncode != 0:
                    st.error("Scoring failed.")
                    st.code(result.stderr or result.stdout)
                    st.stop()

                df = pd.read_csv(output_path / "groups.csv")
                st.session_state["results"] = df

        except Exception as error:
            st.error(f"Unable to analyze file: {error}")

if "results" in st.session_state:
    df = st.session_state["results"]

    st.success("Security analysis completed successfully!")

    high = int((df["tier"] == "high").sum())
    medium = int((df["tier"] == "medium").sum())
    low = int((df["tier"] == "low").sum())

    col1, col2, col3, col4 = st.columns(4)

    col1.metric("Total Groups", len(df))
    col2.metric("High Risk", high)
    col3.metric("Medium Risk", medium)
    col4.metric("Low Risk", low)

    st.subheader("Risk Distribution")

    distribution = pd.DataFrame({
        "Risk Level": ["Low", "Medium", "High"],
        "Count": [low, medium, high],
    })

    st.bar_chart(distribution.set_index("Risk Level"))

    st.subheader("Security Analyst Review Queue")

    review = df[df["tier"].isin(["high", "medium"])].copy()
    review = review.sort_values("score", ascending=False)
    display_columns = {
        "tier": "Risk Level",
        "score": "Risk Score",
        "processName": "Process Name",
        "hostName": "Host Name",
        "behavior": "Suspicious Behavior",
        "privilege": "Elevated Privilege",
        "resource": "Sensitive Resources",
        "supporting": "Supporting Evidence",
    }

    review_display = review[list(display_columns.keys())].rename(
        columns=display_columns
    )

    st.dataframe(
        review_display,
        width="stretch",
        hide_index=True,
    )
  

    st.subheader("Risk Score Explanation")

    if not df.empty:
        selected = st.selectbox(
            "Select an event group",
            df["group_id"].astype(str).tolist(),
        )

        event = df[df["group_id"].astype(str) == selected].iloc[0]

        st.write("Risk Score:", event["score"])
        st.write("Risk Level:", str(event["tier"]).upper())

        factors = {
            "Suspicious Behavior": event["behavior"],
            "Elevated Privilege": event["privilege"],
            "Sensitive Resources": event["resource"],
            "Supporting Evidence": event["supporting"],
        }

        st.table(
            pd.DataFrame(
                list(factors.items()),
                columns=["Risk Factor", "Points"],
            )
        )

        st.caption(
            "Scores are generated by the project's existing "
            "rule-based security scoring engine."
        )

    st.subheader("Export Analysis")

    st.download_button(
        "Download All Scored Results",
        data=df.to_csv(index=False).encode("utf-8"),
        file_name="beth_scored_results.csv",
        mime="text/csv",
    )

    st.download_button(
        "Download Analyst Review Queue",
        data=review.to_csv(index=False).encode("utf-8"),
        file_name="beth_review_queue.csv",
        mime="text/csv",
    )
